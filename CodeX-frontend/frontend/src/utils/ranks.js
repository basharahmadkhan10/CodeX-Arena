export function getRankDetails(rating = 1000) {
  const r = Math.max(0, parseInt(rating) || 0);

  // Find matching tier
  let rank = RANKS_LADDER.find((item) => r >= item.minRp && r <= item.maxRp);
  if (!rank) {
    rank = r >= 4900 ? RANKS_LADDER[RANKS_LADDER.length - 1] : RANKS_LADDER[0];
  }

  // Find next tier
  const currentIndex = RANKS_LADDER.findIndex((item) => item.tier === rank.tier);
  const nextRank = currentIndex < RANKS_LADDER.length - 1 ? RANKS_LADDER[currentIndex + 1] : null;

  // Calculate progress % inside current tier
  let progressPct = 100;
  let rpNeeded = 0;

  if (nextRank) {
    const tierRange = rank.maxRp - rank.minRp + 1;
    const currentProgress = r - rank.minRp;
    progressPct = Math.min(100, Math.max(0, Math.round((currentProgress / tierRange) * 100)));
    rpNeeded = rank.maxRp + 1 - r;
  }

  return {
    ...rank,
    rating: r,
    nextRank,
    progressPct,
    rpNeeded,
    isApex: r >= 4900,
  };
}
